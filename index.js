// index.js:
// Main entry point for the Express backend application.

const express = require('express')
const app = express()
// Middleware to parse incoming JSON payloads in request bodies (e.g., req.body).
app.use(express.json())
// Pull PORT from environment variables (fallback to 3001 if not in .env file).
const PORT = process.env.PORT || 3001
// Import our custom database connection utility and Blog model.
const { connectToDatabase } = require('./utils/db')
const Blog = require('./models/blog')

// API Route: GET all blog objects from the database using the Sequelize Blog model.
app.get('/api/blogs', async (req, res) => {
  // Blog.findAll() translates to SQL: SELECT * FROM blogs.
  const blogs = await Blog.findAll()
  res.json(blogs)
})

// API Route: POST a new blog object to the database.
app.post('/api/blogs', async (req, res) => {
  try {
    // Insert new row in the table using the JSON data sent by the client (req.body). 'await' the database operation to finish.
    const blog = await Blog.create(req.body)
    // If success: send an HTTP 201 (Created) code back to client, with newly created blog object (as JSON), inc. its new Db id.
    res.status(201).json(blog)
    // else: catch error. Problem, e.g., missing a required field like 'url'.
  } catch (error) {
    // Send HTTP 400 (Bad Request) code back with a JSON object containing the specific error message generated by Sequelize/PostgreSQL.
    return res.status(400).json({ error: error.message })
  }
})

// API Route: DELETE a blog from the Db, based on id.
app.delete('/api/blogs/:id', async (req, res) => {
  try {
    // Find the blog by primary key (id) from the URL parameters.
    const blog = await Blog.findByPk(req.params.id)
    
    if (blog) {
      // If found, delete the record from the database
      await blog.destroy()
      // and send 204 (No Content) status on successful deletion.
      res.status(204).end()
    } else {
      // else: send 404 (Not Found).
      res.status(404).json({ error: 'Blog not found' })
    }
    // Catch error:
  } catch (error) {
    // Handle unexpected errors (e.g., malformed id format)
    return res.status(400).json({ error: error.message })
  }
})

// Asynchronous startup function ensures database connection succeeds before starting the server.
const start = async () => {
  // Establish the database connection first.
  await connectToDatabase()
  // Then, start the Express server once the database is successfully connected.
  app.listen(PORT, () => {
    console.log(`Server running on port ${PORT}`)
  })
}
// Boot the application startup process.
start()